import { useEffect, useId, useState } from 'react';
import { Button, Input, Modal } from '../../../components/ui';
import { createSingleFlight } from '../../../lib/singleFlight.js';
import { createBranch, updateBranch } from '../data/branchActions.js';
import { useCurrentPosition } from '../hooks/useCurrentPosition.js';
import { cleanBranchValues, positionProblem, validateBranch } from '../utils/branchRules.js';
import { LocationCapture } from './LocationCapture.jsx';

const FIELDS = ['name', 'address', 'city', 'phone'];
const EMPTY = { name: '', address: '', city: '', phone: '' };
const fromBranch = (branch) => ({ name: branch.name, address: branch.address, city: branch.city, phone: branch.phone });

/**
 * Create a branch (mode "create": details plus its GPS location, captured on this device and
 * confirmed) or edit one (mode "edit": details only; the location has its own dialog). The code
 * is generated by the server and shown read-only. `onSaved(branch)` runs after success.
 */
export function BranchFormModal({ mode, branch, open, onClose, onSaved, cities = [] }) {
  const formId = useId();
  const citiesId = useId();
  const isCreate = mode === 'create';
  const position = useCurrentPosition();
  const [values, setValues] = useState(EMPTY);
  const [errors, setErrors] = useState({});
  const [confirmed, setConfirmed] = useState(false);
  const [formError, setFormError] = useState('');
  const [saving, setSaving] = useState(false);
  // One save at a time: Enter or a click during a save sends nothing more.
  const [saveOnce] = useState(createSingleFlight);
  const resetPosition = position.reset;

  // Fresh form each time it opens.
  useEffect(() => {
    if (!open) return;
    setValues(isCreate || !branch ? EMPTY : fromBranch(branch));
    setErrors({});
    setConfirmed(false);
    setFormError('');
    setSaving(false);
    resetPosition();
  }, [open, isCreate, branch, resetPosition]);

  // A new capture must be confirmed again.
  useEffect(() => setConfirmed(false), [position.position]);

  const set = (field) => (event) => {
    setValues((current) => ({ ...current, [field]: event.target.value }));
    if (errors[field]) setErrors(({ [field]: _removed, ...rest }) => rest);
  };

  function focusFirst(problems) {
    const first = [...FIELDS, 'location'].find((field) => problems[field]);
    if (first) document.getElementById(`${formId}-${first}`)?.focus();
  }

  function submit(event) {
    event.preventDefault();
    return saveOnce(save);
  }

  async function save() {
    setFormError('');
    const cleaned = cleanBranchValues(values, FIELDS);
    const problems = validateBranch(cleaned, FIELDS);
    if (isCreate) {
      const locationProblem = positionProblem(position.position) ?? (confirmed ? null : 'Confirm that this is the branch location.');
      if (locationProblem) problems.location = locationProblem;
    }
    setErrors(problems);
    if (Object.keys(problems).length) {
      focusFirst(problems);
      return;
    }
    setSaving(true);
    try {
      const { latitude, longitude, accuracy } = position.position ?? {};
      const saved = isCreate
        ? await createBranch({ ...cleaned, location: { latitude, longitude, accuracy, confirmed: true } })
        : await updateBranch(branch.id, cleaned);
      setSaving(false);
      onSaved(saved);
    } catch (error) {
      setSaving(false);
      if (error.details) {
        // Location problems arrive as location.latitude etc.; show them on the location block.
        const details = Object.fromEntries(Object.entries(error.details).map(([key, message]) => [key.startsWith('location') ? 'location' : key, message]));
        setErrors(details);
        focusFirst(details);
      } else if (error.status === 404) setFormError('This branch no longer exists.');
      else if (error.code === 'SCHOOL_SUSPENDED') setFormError(error.message);
      else setFormError(error.status === 0 ? error.message : 'The branch could not be saved. Try again.');
    }
  }

  const field = (name, props = {}) => ({ id: `${formId}-${name}`, value: values[name], onChange: set(name), error: errors[name], ...props });

  return (
    <Modal
      open={open}
      onClose={onClose}
      size="lg"
      title={isCreate ? 'Add Branch' : 'Edit Branch'}
      description={isCreate ? 'The branch is active once it is added. Its code is generated automatically.' : `Branch code ${branch?.code ?? ''} cannot be changed.`}
      loading={saving}
      loadingLabel={isCreate ? 'Adding…' : 'Saving…'}
      error={formError}
      footer={
        <>
          <Button variant="outline" onClick={onClose} disabled={saving}>
            Cancel
          </Button>
          <Button type="submit" form={formId} loading={saving}>
            {isCreate ? 'Add Branch' : 'Save Changes'}
          </Button>
        </>
      }
    >
      <form id={formId} onSubmit={submit} noValidate className="grid grid-cols-1 gap-4 sm:grid-cols-2">
        <Input label="Branch name" required autoComplete="off" hint="Unique in your school, whatever the capitalization." {...field('name')} fieldClassName="sm:col-span-2" />
        <Input label="Address" required autoComplete="off" {...field('address')} fieldClassName="sm:col-span-2" />
        <Input label="City" required autoComplete="off" list={citiesId} {...field('city')} />
        <datalist id={citiesId}>
          {cities.map((city) => (
            <option key={city} value={city} />
          ))}
        </datalist>
        <Input label="Phone" type="tel" autoComplete="off" placeholder="+252 61 2345678" hint="Optional." {...field('phone')} />
        {isCreate && (
          <div className="sm:col-span-2">
            <LocationCapture id={`${formId}-location`} capture={position} confirmed={confirmed} onConfirmedChange={setConfirmed} error={errors.location} disabled={saving} />
          </div>
        )}
      </form>
    </Modal>
  );
}
