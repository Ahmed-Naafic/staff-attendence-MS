/**
 * A branch's timetable of an examination: sessions with their papers, rooms (students per section,
 * invigilators, invigilators needed), papers not timetabled, each invigilator's duties, a summary and
 * what can be done. The School Owner names the branch of a school-wide examination.
 */
export async function getTimetable(scope, examId, { branch: branchId }) {
  const prisma = getPrisma();
  const [{ exam, branch }, today] = await Promise.all([context(prisma, scope, examId, branchId), calendarToday()]);
  const [timetable, sessions, papers, sections, settings, branches] = await Promise.all([
    prisma.examTimetable.findUnique({ where: { examinationId_branchId: { examinationId: exam.id, branchId: branch.id } } }),
    prisma.examSession.findMany({
      where: { examinationId: exam.id, branchId: branch.id },
      orderBy: [{ date: 'asc' }, { startMinute: 'asc' }],
      select: {
        id: true,
        date: true,
        shiftName: true,
        sequence: true,
        startMinute: true,
        endMinute: true,
        sittings: { select: { id: true, paperId: true } },
        seats: { select: { roomId: true, sectionId: true } },
        invigilations: { select: { roomId: true, staff: { select: { id: true, name: true, staffId: true } } } },
      },
    }),
    prisma.examPaper.findMany({ where: { examinationId: exam.id }, select: { id: true, classId: true, durationMinutes: true, maxMarks: true, class: { select: { name: true, sequence: true } }, subject: { select: { id: true, name: true, code: true } }, sittings: { where: { branchId: branch.id }, select: { id: true } } } }),
    loadSections(prisma, exam, branch.id),
    effectiveExamSettings(scope.school.id, branch.id, prisma),
    !scope.branch && !exam.branchId ? prisma.branch.findMany({ where: { schoolId: scope.school.id, status: 'ACTIVE' }, select: { id: true, name: true, code: true }, orderBy: { name: 'asc' } }) : [],
  ]);
  const roomIds = [...new Set(sessions.flatMap((s) => [...s.seats.map((x) => x.roomId), ...s.invigilations.map((i) => i.roomId)]))];
  const rooms = new Map((roomIds.length ? await prisma.examRoom.findMany({ where: { id: { in: roomIds } }, select: { id: true, name: true, defaultCapacity: true } }) : []).map((r) => [r.id, r]));
  const sectionName = new Map(sections.map((s) => [s.id, s.name]));
  const studentsOfClass = (classId) => sections.filter((s) => s.classId === classId).reduce((n, s) => n + s.students.length, 0);
  const paperOf = new Map(papers.map((p) => [p.id, p]));
  const need = (n) => Math.max(1, Math.ceil(n / settings.studentsPerInvigilator));
  const load = new Map();

  const shaped = sessions.map((s) => {
    const date = toDay(s.date);
    const byRoom = new Map();
    for (const seat of s.seats) {
      const room = byRoom.get(seat.roomId) ?? { students: 0, sections: new Map(), invigilators: [] };
      room.students += 1;
      room.sections.set(seat.sectionId, (room.sections.get(seat.sectionId) ?? 0) + 1);
      byRoom.set(seat.roomId, room);
    }
    for (const i of s.invigilations) {
      const room = byRoom.get(i.roomId) ?? { students: 0, sections: new Map(), invigilators: [] };
      room.invigilators.push(i.staff);
      byRoom.set(i.roomId, room);
      load.set(i.staff.id, { staff: i.staff, duties: (load.get(i.staff.id)?.duties ?? 0) + 1 });
    }
    return {
      id: s.id,
      date,
      shiftName: s.shiftName,
      sequence: s.sequence,
      start: toClock(s.startMinute),
      end: toClock(s.endMinute),
      past: date < today,
      students: s.seats.length,
      papers: s.sittings
        .map((x) => {
          const p = paperOf.get(x.paperId);
          return { sittingId: x.id, paperId: p.id, class: { id: p.classId, name: p.class.name, sequence: p.class.sequence }, subject: p.subject, durationMinutes: p.durationMinutes, students: s.seats.length ? studentsOfClass(p.classId) : 0 };
        })
        .sort((a, b) => a.class.sequence - b.class.sequence),
      rooms: [...byRoom.entries()]
        .map(([roomId, r]) => ({
          room: { id: roomId, name: rooms.get(roomId)?.name ?? '?', capacity: rooms.get(roomId)?.defaultCapacity ?? 0 },
          students: r.students,
          sections: [...r.sections.entries()].map(([id, count]) => ({ id, name: sectionName.get(id) ?? 'Section', count })),
          invigilators: r.invigilators.sort((a, b) => a.name.localeCompare(b.name)),
          need: r.students ? need(r.students) : 0,
        }))
        .sort((a, b) => a.room.name.localeCompare(b.room.name, undefined, { numeric: true })),
    };
  });
  const unscheduled = papers
    .filter((p) => !p.sittings.length)
    .map((p) => ({ paperId: p.id, class: { id: p.classId, name: p.class.name }, subject: p.subject, students: studentsOfClass(p.classId) }))
    .sort((a, b) => a.class.name.localeCompare(b.class.name) || a.subject.name.localeCompare(b.subject.name));
  const roomsShort = shaped.flatMap((s) => s.rooms).filter((r) => r.invigilators.length < r.need).length;
  const started = exam.status === 'SCHEDULED' && toDay(exam.startDate) < today;
  const canEdit = exam.status !== 'CANCELLED' && exam.academicYear.status !== 'CLOSED';
  return {
    examination: { id: exam.id, name: exam.name, state: examState({ status: exam.status, startDate: toDay(exam.startDate), endDate: toDay(exam.endDate) }, today), startDate: toDay(exam.startDate), endDate: toDay(exam.endDate), level: exam.branchId ? 'branch' : 'school' },
    branch: brief(branch),
    branches,
    today,
    timetable: timetable && {
      config: { ...timetable.config, shifts: (timetable.config.shifts ?? []).map((s) => ({ ...s, start: toClock(s.start) })) },
      generatedAt: timetable.generatedAt.toISOString(),
      generatedBy: timetable.generatedByName ?? null,
      publishedAt: timetable.publishedAt?.toISOString() ?? null,
      changedSincePublish: Boolean(timetable.publishedAt && timetable.updatedAt.getTime() - timetable.publishedAt.getTime() > 1000),
    },
    settings: { studentsPerInvigilator: settings.studentsPerInvigilator, roomsPerInvigilator: settings.roomsPerInvigilator, avoidOwnSubject: settings.avoidOwnSubject, maxPapersPerDay: settings.maxPapersPerDay, distribution: settings.distributionMethod },
    actions: {
      generate: canEdit && !started,
      clear: canEdit && !started && Boolean(timetable),
      edit: canEdit && Boolean(timetable),
      publish: canEdit && exam.status === 'SCHEDULED' && Boolean(timetable) && !unscheduled.some((u) => u.students) && roomsShort === 0,
    },
    sessions: shaped,
    unscheduled,
    staffLoad: [...load.values()].sort((a, b) => b.duties - a.duties || a.staff.name.localeCompare(b.staff.name)),
    summary: {
      sessions: shaped.length,
      days: new Set(shaped.map((s) => s.date)).size,
      papers: papers.length,
      timetabled: papers.length - unscheduled.length,
      students: sections.reduce((n, s) => n + s.students.length, 0),
      invigilations: shaped.reduce((n, s) => n + s.rooms.reduce((m, r) => m + r.invigilators.length, 0), 0),
      roomsWithoutEnoughInvigilators: roomsShort,
    },
  };
}

/** What the generate form offers: the branch's rooms and staff, the examination's school days there, defaults. */
export async function timetableOptions(scope, examId, { branch: branchId }) {
  const prisma = getPrisma();
  const { exam, branch } = await context(prisma, scope, examId, branchId);
  const from = toDay(exam.startDate);
  const to = toDay(exam.endDate);
  const [rooms, sections, days, settings, timetable] = await Promise.all([
    prisma.examRoom.findMany({ where: { branchId: branch.id, status: 'ACTIVE' }, select: { id: true, name: true, defaultCapacity: true }, orderBy: { nameKey: 'asc' } }),
    loadSections(prisma, exam, branch.id),
    loadSchoolDays({ id: branch.id, schoolId: scope.school.id }, from, to, prisma),
    effectiveExamSettings(scope.school.id, branch.id, prisma),
    prisma.examTimetable.findUnique({ where: { examinationId_branchId: { examinationId: exam.id, branchId: branch.id } } }),
  ]);
  const staff = await loadStaff(prisma, exam, branch.id, sections.map((s) => s.id));
  const config = timetable?.config;
  return {
    branch: brief(branch),
    rooms: rooms.map((r) => ({ id: r.id, name: r.name, capacity: r.defaultCapacity })),
    staff: staff.map((s) => ({ id: s.id, name: s.name, staffId: s.staffId, jobTitle: s.jobTitle ?? null, teaches: s.teaches.size })),
    days: days.map((d) => ({ date: d.date, schoolDay: d.schoolDay, reason: d.reason })),
    students: sections.reduce((n, s) => n + s.students.length, 0),
    largestClass: Math.max(0, ...exam.classes.map((c) => sections.filter((s) => s.classId === c.class.id).reduce((n, s) => n + s.students.length, 0))),
    defaults: {
      shifts: config?.shifts?.map((s) => ({ ...s, start: toClock(s.start) })) ?? [{ name: 'Morning', start: '08:00', sessions: 2 }],
      gapMinutes: config?.gapMinutes ?? 30,
      rooms: config?.rooms ?? rooms.map((r) => ({ roomId: r.id, capacity: null })),
      useAllRooms: config?.useAllRooms ?? false,
      excludedStaff: config?.excludedStaff ?? [],
      distribution: config?.distribution ?? settings.distributionMethod,
      maxPapersPerDay: config?.maxPapersPerDay ?? settings.maxPapersPerDay,
    },
    settings: { studentsPerInvigilator: settings.studentsPerInvigilator, roomsPerInvigilator: settings.roomsPerInvigilator, avoidOwnSubject: settings.avoidOwnSubject },
  };
}

