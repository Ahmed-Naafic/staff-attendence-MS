/** Rooms of the config: active rooms of the branch with their seats for this examination. */
async function configRooms(client, branchId, chosen) {
  const rows = await client.examRoom.findMany({ where: { id: { in: chosen.map((r) => r.roomId) }, branchId, status: 'ACTIVE' }, select: { id: true, name: true, defaultCapacity: true } });
  if (rows.length !== chosen.length) throw badRequest('Check the highlighted fields.', { rooms: 'Choose active rooms of this branch.' });
  return chosen.map((c) => {
    const r = rows.find((x) => x.id === c.roomId);
    return { id: r.id, name: r.name, capacity: c.capacity ?? r.defaultCapacity };
  });
}

/** Seats one session's sittings: groups (section × sitting) into the free rooms. */
function seatGroups(sittings, sections, papersById) {
  return sittings.flatMap((sitting) => {
    const paper = papersById.get(sitting.paperId);
    return sections.filter((s) => s.classId === paper.classId && s.students.length).map((s) => ({ key: `${sitting.id}|${s.id}`, sittingId: sitting.id, sectionId: s.id, subjectId: paper.subjectId, students: s.students }));
  });
}

/**
 * Generates (or regenerates) a branch's timetable before the examination starts: places the papers,
 * times the sessions, seats the students and gives every room its invigilators. Replaces what was
 * there (and unpublishes it). → { ...getTimetable, report: { unplaced, unseated, shortfall } }.
 */
export async function generateTimetable(scope, examId, { branch: branchId }, values, user, req) {
  const today = await calendarToday();
  const report = await withExamLock(scope, async (tx) => {
    const { exam, branch } = await context(tx, scope, examId, branchId);
    writable(exam);
    if (exam.status === 'SCHEDULED' && toDay(exam.startDate) < today) throw conflict('EXAM_STARTED', `${exam.name} has started: its timetable can only be adjusted, not generated again.`);
    const from = toDay(exam.startDate);
    const to = toDay(exam.endDate);
    const settings = await effectiveExamSettings(scope.school.id, branch.id, tx);
    const [rooms, sections, calendar, papers, others] = await Promise.all([
      configRooms(tx, branch.id, values.rooms),
      loadSections(tx, exam, branch.id),
      loadSchoolDays({ id: branch.id, schoolId: scope.school.id }, from, to, tx),
      tx.examPaper.findMany({ where: { examinationId: exam.id }, select: { id: true, classId: true, subjectId: true, durationMinutes: true } }),
      loadOtherSessions(tx, exam, branch.id, from, to),
    ]);
    const days = calendar.filter((d) => d.schoolDay && d.date >= today).map((d) => d.date);
    if (!days.length) throw conflict('NO_EXAM_DAYS', `${branch.name} has no school days from ${from} to ${to} (from today). Check the academic calendar or the examination’s dates.`);
    if (!papers.length) throw conflict('NO_PAPERS', `${exam.name} has no papers yet.`);
    const staffAll = await loadStaff(tx, exam, branch.id, sections.map((s) => s.id));
    const staff = staffAll.filter((s) => !values.excludedStaff.includes(s.id));
    const studentsOf = (classId) => sections.filter((s) => s.classId === classId).reduce((n, s) => n + s.students.length, 0);
    const capacity = rooms.reduce((n, r) => n + r.capacity, 0);
    const maxPapersPerDay = values.maxPapersPerDay ?? settings.maxPapersPerDay;
    const distribution = values.distribution ?? settings.distributionMethod;
    const seed = randomInt(1, 2 ** 31 - 1);

    const plan = planPapers({ days, shifts: values.shifts, papers: papers.map((p) => ({ ...p, students: studentsOf(p.classId) })), maxPapersPerDay, capacity });
    let timed;
    try {
      timed = sessionTimes(plan.slots, values.shifts, values.gapMinutes, (id) => papers.find((p) => p.id === id).durationMinutes);
    } catch (error) {
      if (error.code === 'PAST_MIDNIGHT') throw badRequest('Check the highlighted fields.', { shifts: `The sessions of ${error.date} run past midnight: start earlier, use fewer sessions per shift or shorter gaps.` });
      throw error;
    }

    // Sessions, sittings and seats (rooms busy elsewhere at the same time are left out).
    const papersById = new Map(papers.map((p) => [p.id, p]));
    const sessionRows = [];
    const sittingRows = [];
    const seatRows = [];
    const unseated = [];
    const forStaff = [];
    for (const t of timed) {
      const id = randomUUID();
      const busy = others.filter((o) => overlaps(o, t));
      const free = rooms.filter((r) => !busy.some((o) => o.rooms.has(r.id)));
      const sittings = t.paperIds.map((paperId) => ({ id: randomUUID(), sessionId: id, paperId, branchId: branch.id }));
      const groups = seatGroups(sittings, sections, papersById);
      const seated = seatSession({ rooms: free, groups, distribution, seed: sessionSeed(seed, t.date, t.sequence), useAllRooms: values.useAllRooms });
      sessionRows.push({ id, schoolId: scope.school.id, examinationId: exam.id, branchId: branch.id, date: asDbDay(t.date), shiftName: t.shiftName, sequence: t.sequence, startMinute: t.startMinute, endMinute: t.endMinute });
      sittingRows.push(...sittings);
      seatRows.push(...seated.seats.map((s) => ({ id: randomUUID(), sessionId: id, sittingId: s.sittingId, roomId: s.roomId, studentId: s.studentId, sectionId: s.sectionId, seatNumber: s.seatNumber })));
      unseated.push(...seated.unseated.map((studentId) => ({ date: t.date, studentId })));
      const subjectsOf = (roomId) => {
        const keys = new Set(seated.seats.filter((s) => s.roomId === roomId).map((s) => `${s.sectionId}|${papersById.get(sittings.find((x) => x.id === s.sittingId).paperId).subjectId}`));
        return [...keys].map((k) => ({ sectionId: k.split('|')[0], subjectId: k.split('|')[1] }));
      };
      forStaff.push({ id, date: t.date, startMinute: t.startMinute, endMinute: t.endMinute, busyStaff: busy.flatMap((o) => [...o.staff]), rooms: seated.rooms.map((r) => ({ roomId: r.id, students: r.students, subjects: subjectsOf(r.id) })) });
    }
    const busyStaff = new Set(forStaff.flatMap((s) => s.busyStaff.map((p) => `${p}|${s.id}`)));
    const { assignments, shortfall } = assignInvigilators({ sessions: forStaff, staff, busy: busyStaff, settings });

    await deleteRows(tx, exam.id, branch.id);
    if (sessionRows.length) await tx.examSession.createMany({ data: sessionRows });
    if (sittingRows.length) await tx.examSitting.createMany({ data: sittingRows });
    if (seatRows.length) await tx.examSeat.createMany({ data: seatRows });
    if (assignments.length) await tx.examInvigilation.createMany({ data: assignments.map((a) => ({ id: randomUUID(), ...a })) });
    const config = { shifts: values.shifts, gapMinutes: values.gapMinutes, rooms: values.rooms, useAllRooms: values.useAllRooms, excludedStaff: values.excludedStaff, distribution, maxPapersPerDay, seed };
    const now = new Date();
    await tx.examTimetable.upsert({
      where: { examinationId_branchId: { examinationId: exam.id, branchId: branch.id } },
      create: { schoolId: scope.school.id, examinationId: exam.id, branchId: branch.id, config, generatedAt: now, generatedById: user.id, generatedByName: user.name },
      update: { config, generatedAt: now, generatedById: user.id, generatedByName: user.name, publishedAt: null },
    });
    const result = {
      unplaced: plan.unplaced.map((u) => ({ ...u, students: studentsOf(papersById.get(u.paperId).classId) })),
      unseated: unseated.length,
      shortfall: shortfall.reduce((n, s) => n + s.missing, 0),
    };
    await audit(tx, scope, user, req, AUDIT_ACTIONS.EXAM_TIMETABLE_GENERATED, exam, branch, `Generated the ${branch.name} timetable of ${exam.name}: ${sessionRows.length} sessions, ${sittingRows.length} papers, ${seatRows.length} seats, ${assignments.length} invigilations.`, {
      fields: ['timetable'],
      branch: branch.name,
      sessions: sessionRows.length,
      papers: sittingRows.length,
      seats: seatRows.length,
      invigilations: assignments.length,
      ...result,
    });
    return result;
  });
  return { ...(await getTimetable(scope, examId, { branch: branchId })), report };
}

/** Removes a branch's timetable before the examination starts. */
export async function clearTimetable(scope, examId, { branch: branchId }, user, req) {
  const today = await calendarToday();
  await withExamLock(scope, async (tx) => {
    const { exam, branch } = await context(tx, scope, examId, branchId);
    writable(exam);
    if (exam.status === 'SCHEDULED' && toDay(exam.startDate) < today) throw conflict('EXAM_STARTED', `${exam.name} has started: its timetable is kept.`);
    const existing = await tx.examTimetable.findUnique({ where: { examinationId_branchId: { examinationId: exam.id, branchId: branch.id } } });
    if (!existing) throw notFound('There is no timetable to clear.');
    await deleteRows(tx, exam.id, branch.id);
    await tx.examTimetable.delete({ where: { id: existing.id } });
    await audit(tx, scope, user, req, AUDIT_ACTIONS.EXAM_TIMETABLE_CLEARED, exam, branch, `Cleared the ${branch.name} timetable of ${exam.name}.`, { fields: ['timetable'], branch: branch.name });
  });
  return getTimetable(scope, examId, { branch: branchId });
}

