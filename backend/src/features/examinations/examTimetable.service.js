/**
 * Before papers are removed (a paper, or a class's papers): refuses papers sat before today (409
 * PAPER_SAT); removes their sittings and seats in every branch, and sessions left empty.
 */
export async function dropPaperSittings(tx, paperIds, today) {
  if (!paperIds.length) return;
  const sittings = await tx.examSitting.findMany({ where: { paperId: { in: paperIds } }, select: { id: true, sessionId: true, session: { select: { date: true } } } });
  if (sittings.some((s) => toDay(s.session.date) < today)) throw conflict('PAPER_SAT', 'This paper was already sat: it stays in the examination.');
  if (!sittings.length) return;
  const ids = sittings.map((s) => s.id);
  await refuseIfAttendance(tx, { sittingId: { in: ids } });
  await tx.examSeat.deleteMany({ where: { sittingId: { in: ids } } });
  await tx.examSitting.deleteMany({ where: { id: { in: ids } } });
  const empty = await tx.examSession.findMany({ where: { id: { in: [...new Set(sittings.map((s) => s.sessionId))] }, sittings: { none: {} } }, select: { id: true } });
  if (empty.length) {
    await tx.examInvigilation.deleteMany({ where: { sessionId: { in: empty.map((e) => e.id) } } });
    await tx.examSession.deleteMany({ where: { id: { in: empty.map((e) => e.id) } } });
  }
}

/** After a paper's length changes: its sessions (not past) end with their longest paper, without running into the next. */
export async function refitPaperSessions(tx, paperId, today) {
  const sittings = await tx.examSitting.findMany({ where: { paperId }, select: { session: { select: { id: true, examinationId: true, branchId: true, date: true, startMinute: true, endMinute: true, sittings: { select: { paper: { select: { durationMinutes: true } } } } } } } });
  for (const { session: s } of sittings) {
    if (toDay(s.date) < today) continue;
    const end = s.startMinute + Math.max(...s.sittings.map((x) => x.paper.durationMinutes));
    if (end === s.endMinute) continue;
    if (end > 1440) throw conflict('PAST_MIDNIGHT', 'Its session would run past midnight.');
    const clash = await tx.examSession.findFirst({ where: { examinationId: s.examinationId, branchId: s.branchId, date: s.date, id: { not: s.id }, startMinute: { lt: end }, endMinute: { gt: s.startMinute } } });
    if (clash) throw conflict('SESSION_OVERLAP', `Its session on ${toDay(s.date)} would run into the ${toClock(clash.startMinute)} session. Move one of them first.`);
    await tx.examSession.update({ where: { id: s.id }, data: { endMinute: end } });
  }
}

/** Whether an examination has any timetable rows (its dates and branches then stay). */
export async function hasTimetable(tx, examId) {
  return Boolean(await tx.examSession.findFirst({ where: { examinationId: examId }, select: { id: true } }));
}

