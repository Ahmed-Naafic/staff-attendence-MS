/**
 * Re-seats and re-staffs `sessionIds` of a timetable (after a paper moved): rooms from the
 * timetable's choices minus those busy elsewhere, invigilators with everyone's other duties counted.
 * Refuses (409 NOT_ENOUGH_SEATS) when a session's students no longer fit.
 */
async function redoSessions(tx, scope, exam, branch, timetable, sessionIds) {
  const settings = await effectiveExamSettings(scope.school.id, branch.id, tx);
  const config = timetable.config;
  const rooms = await configRooms(tx, branch.id, config.rooms);
  const sections = await loadSections(tx, exam, branch.id);
  const sessions = await tx.examSession.findMany({ where: { id: { in: sessionIds } }, include: { sittings: { include: { paper: { select: { id: true, classId: true, subjectId: true, durationMinutes: true } } } } } });
  const from = toDay(exam.startDate);
  const to = toDay(exam.endDate);
  const others = await loadOtherSessions(tx, exam, branch.id, from, to);
  await refuseIfAttendance(tx, { sessionId: { in: sessionIds } });
  await tx.examInvigilation.deleteMany({ where: { sessionId: { in: sessionIds } } });
  await tx.examSeat.deleteMany({ where: { sessionId: { in: sessionIds } } });
  const forStaff = [];
  for (const s of sessions) {
    if (!s.sittings.length) {
      await tx.examSession.delete({ where: { id: s.id } });
      continue;
    }
    const plain = { date: toDay(s.date), startMinute: s.startMinute, endMinute: s.startMinute + Math.max(...s.sittings.map((x) => x.paper.durationMinutes)) };
    if (plain.endMinute > 1440) throw conflict('PAST_MIDNIGHT', 'This session would run past midnight.');
    // The session must not run into the next session of the day.
    const clash = await tx.examSession.findFirst({ where: { examinationId: exam.id, branchId: branch.id, date: s.date, id: { not: s.id }, startMinute: { lt: plain.endMinute }, endMinute: { gt: plain.startMinute } } });
    if (clash) throw conflict('SESSION_OVERLAP', `The session would run into the ${toClock(clash.startMinute)} session of ${plain.date}.`);
    if (plain.endMinute !== s.endMinute) await tx.examSession.update({ where: { id: s.id }, data: { endMinute: plain.endMinute } });
    const busy = others.filter((o) => overlaps(o, plain));
    const free = rooms.filter((r) => !busy.some((o) => o.rooms.has(r.id)));
    const papersById = new Map(s.sittings.map((x) => [x.paper.id, x.paper]));
    const groups = seatGroups(s.sittings.map((x) => ({ id: x.id, paperId: x.paper.id })), sections, papersById);
    const seated = seatSession({ rooms: free, groups, distribution: config.distribution, seed: sessionSeed(config.seed, plain.date, s.sequence), useAllRooms: config.useAllRooms });
    if (seated.unseated.length) throw conflict('NOT_ENOUGH_SEATS', `The rooms of this timetable cannot seat the ${seated.unseated.length + seated.seats.length} students of that session.`);
    if (seated.seats.length) await tx.examSeat.createMany({ data: seated.seats.map((x) => ({ sessionId: s.id, sittingId: x.sittingId, roomId: x.roomId, studentId: x.studentId, sectionId: x.sectionId, seatNumber: x.seatNumber })) });
    const subjectOf = new Map(s.sittings.map((x) => [x.id, x.paper.subjectId]));
    forStaff.push({
      id: s.id,
      date: plain.date,
      busyStaff: busy.flatMap((o) => [...o.staff]),
      rooms: seated.rooms.map((r) => ({ roomId: r.id, students: r.students, subjects: [...new Set(seated.seats.filter((x) => x.roomId === r.id).map((x) => `${x.sectionId}|${subjectOf.get(x.sittingId)}`))].map((k) => ({ sectionId: k.split('|')[0], subjectId: k.split('|')[1] })) })),
    });
  }
  const staff = (await loadStaff(tx, exam, branch.id, sections.map((x) => x.id))).filter((p) => !(config.excludedStaff ?? []).includes(p.id));
  const held = await tx.examInvigilation.groupBy({ by: ['staffId'], where: { session: { examinationId: exam.id, branchId: branch.id } }, _count: { _all: true } });
  const busy = new Set(forStaff.flatMap((s) => s.busyStaff.map((p) => `${p}|${s.id}`)));
  const { assignments } = assignInvigilators({ sessions: forStaff, staff, busy, load: new Map(held.map((h) => [h.staffId, h._count._all])), settings });
  if (assignments.length) await tx.examInvigilation.createMany({ data: assignments });
}

/** Renumbers a day's sessions of the timetable 1, 2, … by start time. */
async function renumberDay(tx, examId, branchId, date) {
  const rows = await tx.examSession.findMany({ where: { examinationId: examId, branchId, date }, orderBy: { startMinute: 'asc' }, select: { id: true, sequence: true } });
  for (const [i, r] of rows.entries()) if (r.sequence !== i + 1) await tx.examSession.update({ where: { id: r.id }, data: { sequence: i + 1 } });
}

/**
 * Moves a paper to another session of the timetable, or to a new session at a date and time. Both
 * sessions are re-seated and re-staffed. Past sessions stay; a class sits one paper per session and
 * at most the papers a day allowed.
 */
export async function moveSitting(scope, examId, sittingId, { branch: branchId }, target, user, req) {
  const today = await calendarToday();
  await withExamLock(scope, async (tx) => {
    const { exam, branch } = await context(tx, scope, examId, branchId);
    writable(exam);
    const timetable = await tx.examTimetable.findUnique({ where: { examinationId_branchId: { examinationId: exam.id, branchId: branch.id } } });
    const sitting = isUuid(sittingId) ? await tx.examSitting.findFirst({ where: { id: sittingId, branchId: branch.id, session: { examinationId: exam.id } }, include: { session: true, paper: { include: { class: { select: { name: true } }, subject: { select: { name: true } } } } } }) : null;
    if (!timetable || !sitting) throw notFound('Paper not found in this timetable.');
    const fromDay = toDay(sitting.session.date);
    if (fromDay < today) throw conflict('SESSION_PAST', 'This paper was sat on a day before today and stays as it is.');
    const settings = await effectiveExamSettings(scope.school.id, branch.id, tx);
    const maxPerDay = timetable.config.maxPapersPerDay ?? settings.maxPapersPerDay;

    let session;
    if (target.session) {
      session = await tx.examSession.findFirst({ where: { id: target.session, examinationId: exam.id, branchId: branch.id } });
      if (!session) throw badRequest('Check the highlighted fields.', { session: 'Choose a session of this timetable.' });
      if (session.id === sitting.sessionId) throw badRequest('Check the highlighted fields.', { session: 'The paper is already in this session.' });
    } else {
      if (target.date < today) throw badRequest('Check the highlighted fields.', { date: `Choose ${today} or later.` });
      if (target.date < toDay(exam.startDate) || target.date > toDay(exam.endDate)) throw badRequest('Check the highlighted fields.', { date: `Within the examination: ${toDay(exam.startDate)} to ${toDay(exam.endDate)}.` });
      const [day] = await loadSchoolDays({ id: branch.id, schoolId: scope.school.id }, target.date, target.date, tx);
      if (!day.schoolDay) throw conflict('NOT_A_SCHOOL_DAY', `${target.date} is not a school day in ${branch.name}.`);
      const shift = [...timetable.config.shifts].reverse().find((s) => s.start <= target.start) ?? timetable.config.shifts[0];
      session = await tx.examSession.create({ data: { schoolId: scope.school.id, examinationId: exam.id, branchId: branch.id, date: asDbDay(target.date), shiftName: shift.name, sequence: 99, startMinute: target.start, endMinute: Math.min(1440, target.start + sitting.paper.durationMinutes) } });
    }
    const toDate = toDay(session.date);
    if (toDate < today) throw conflict('SESSION_PAST', 'That session was on a day before today.');
    const classId = sitting.paper.classId;
    const inTarget = await tx.examSitting.findFirst({ where: { sessionId: session.id, paper: { classId } } });
    if (inTarget) throw conflict('CLASS_BUSY', `${sitting.paper.class.name} already sits a paper in that session.`);
    const sameDay = await tx.examSitting.count({ where: { branchId: branch.id, id: { not: sitting.id }, paper: { classId }, session: { examinationId: exam.id, date: session.date } } });
    if (sameDay >= maxPerDay) throw conflict('TOO_MANY_PAPERS', `${sitting.paper.class.name} would sit more than ${maxPerDay} paper${maxPerDay === 1 ? '' : 's'} on ${toDate}.`);

    await tx.examSitting.update({ where: { id: sitting.id }, data: { sessionId: session.id } });
    await redoSessions(tx, scope, exam, branch, timetable, [sitting.sessionId, session.id]);
    await renumberDay(tx, exam.id, branch.id, sitting.session.date);
    if (toDate !== fromDay) await renumberDay(tx, exam.id, branch.id, session.date);
    await touch(tx, exam.id, branch.id);
    await audit(tx, scope, user, req, AUDIT_ACTIONS.EXAM_TIMETABLE_CHANGED, exam, branch, `Moved the ${sitting.paper.subject.name} paper of ${sitting.paper.class.name} to ${toDate} ${toClock(session.startMinute)} (${branch.name}).`, {
      fields: ['sessions'],
      paper: `${sitting.paper.class.name} · ${sitting.paper.subject.name}`,
      from: `${fromDay} ${toClock(sitting.session.startMinute)}`,
      to: `${toDate} ${toClock(session.startMinute)}`,
    });
  });
  return getTimetable(scope, examId, { branch: branchId });
}

/**
 * Sets a room's invigilators in a session (replacing them): active staff of the branch, not in another
 * room of the session nor busy in another examination at that time. Past sessions stay.
 */
export async function setInvigilators(scope, examId, sessionId, { branch: branchId }, { room, staff }, user, req) {
  const today = await calendarToday();
  await withExamLock(scope, async (tx) => {
    const { exam, branch } = await context(tx, scope, examId, branchId);
    writable(exam);
    const session = isUuid(sessionId) ? await tx.examSession.findFirst({ where: { id: sessionId, examinationId: exam.id, branchId: branch.id } }) : null;
    if (!session) throw notFound('Session not found.');
    if (toDay(session.date) < today) throw conflict('SESSION_PAST', 'This session was on a day before today and stays as it is.');
    const used = await tx.examSeat.findFirst({ where: { sessionId: session.id, roomId: room }, select: { id: true } });
    const roomRow = await tx.examRoom.findFirst({ where: { id: room, branchId: branch.id }, select: { id: true, name: true } });
    if (!roomRow || !used) throw badRequest('Check the highlighted fields.', { room: 'Choose a room used in this session.' });
    const people = await tx.user.findMany({ where: { id: { in: staff }, role: 'STAFF', status: 'ACTIVE', branchId: branch.id }, select: { id: true, name: true } });
    if (people.length !== staff.length) throw badRequest('Check the highlighted fields.', { staff: 'Choose active staff of this branch.' });
    const elsewhere = await tx.examInvigilation.findFirst({ where: { sessionId: session.id, roomId: { not: room }, staffId: { in: staff } }, include: { staff: { select: { name: true } }, room: { select: { name: true } } } });
    if (elsewhere) throw conflict('STAFF_BUSY', `${elsewhere.staff.name} already invigilates ${elsewhere.room.name} in this session.`);
    const clash = await tx.examInvigilation.findFirst({
      where: { staffId: { in: staff }, session: { branchId: branch.id, examinationId: { not: exam.id }, examination: { status: { not: 'CANCELLED' } }, date: session.date, startMinute: { lt: session.endMinute }, endMinute: { gt: session.startMinute } } },
      include: { staff: { select: { name: true } }, session: { include: { examination: { select: { name: true } } } } },
    });
    if (clash) throw conflict('STAFF_BUSY', `${clash.staff.name} invigilates ${clash.session.examination.name} at that time.`);
    const before = await tx.examInvigilation.findMany({ where: { sessionId: session.id, roomId: room }, include: { staff: { select: { name: true } } } });
    await tx.examInvigilation.deleteMany({ where: { sessionId: session.id, roomId: room } });
    if (staff.length) await tx.examInvigilation.createMany({ data: staff.map((staffId) => ({ sessionId: session.id, roomId: room, staffId })) });
    await touch(tx, exam.id, branch.id);
    await audit(tx, scope, user, req, AUDIT_ACTIONS.EXAM_TIMETABLE_CHANGED, exam, branch, `Set the invigilators of ${roomRow.name} on ${toDay(session.date)} ${toClock(session.startMinute)}: ${people.map((p) => p.name).join(', ') || 'none'}.`, {
      fields: ['invigilators'],
      room: roomRow.name,
      from: before.map((b) => b.staff.name),
      to: people.map((p) => p.name),
    });
  });
  return getTimetable(scope, examId, { branch: branchId });
}

/** A session's rooms with each seat: { session, rooms: [{ room, seats: [{ seatNumber, student, section, subject }] }] }. */
export async function sessionSeats(scope, examId, sessionId, { branch: branchId }) {
  const prisma = getPrisma();
  const { exam, branch } = await context(prisma, scope, examId, branchId);
  const session = isUuid(sessionId) ? await prisma.examSession.findFirst({ where: { id: sessionId, examinationId: exam.id, branchId: branch.id } }) : null;
  if (!session) throw notFound('Session not found.');
  const seats = await prisma.examSeat.findMany({
    where: { sessionId: session.id },
    orderBy: [{ seatNumber: 'asc' }],
    select: {
      seatNumber: true,
      room: { select: { id: true, name: true } },
      student: { select: { id: true, firstName: true, middleName: true, lastName: true, studentNumber: true } },
      section: { select: { id: true, name: true, class: { select: { name: true } } } },
      sitting: { select: { paper: { select: { subject: { select: { name: true } } } } } },
    },
  });
  const rooms = new Map();
  for (const s of seats) {
    const r = rooms.get(s.room.id) ?? { room: s.room, seats: [] };
    r.seats.push({ seatNumber: s.seatNumber, student: { id: s.student.id, name: studentName(s.student), number: s.student.studentNumber }, section: { id: s.section.id, name: sectionDisplayName(s.section.class.name, s.section.name) }, subject: s.sitting.paper.subject.name });
    rooms.set(s.room.id, r);
  }
  return {
    session: { id: session.id, date: toDay(session.date), start: toClock(session.startMinute), end: toClock(session.endMinute), shiftName: session.shiftName },
    rooms: [...rooms.values()].sort((a, b) => a.room.name.localeCompare(b.room.name, undefined, { numeric: true })),
  };
}

/**
 * Publishes a branch's timetable of a scheduled examination: every paper with students timetabled and
 * every room with an invigilator. Each invigilator is told their duties (when the school's setting says so).
 */
export async function publishTimetable(scope, examId, { branch: branchId }, user, req) {
  await withExamLock(scope, async (tx) => {
    const { exam, branch } = await context(tx, scope, examId, branchId);
    writable(exam);
    if (exam.status !== 'SCHEDULED') throw conflict('NOT_SCHEDULED', `Schedule ${exam.name} before publishing its timetable.`);
    const timetable = await tx.examTimetable.findUnique({ where: { examinationId_branchId: { examinationId: exam.id, branchId: branch.id } } });
    if (!timetable) throw notFound('There is no timetable to publish.');
    const sections = await loadSections(tx, exam, branch.id);
    const missing = await tx.examPaper.findMany({ where: { examinationId: exam.id, sittings: { none: { branchId: branch.id } } }, select: { classId: true, class: { select: { name: true } }, subject: { select: { name: true } } } });
    const withStudents = missing.filter((p) => sections.some((s) => s.classId === p.classId && s.students.length));
    if (withStudents.length) throw conflict('PAPERS_NOT_TIMETABLED', `Timetable every paper first: ${withStudents.map((p) => `${p.class.name} ${p.subject.name}`).join(', ')}.`);
    const sessions = await tx.examSession.findMany({
      where: { examinationId: exam.id, branchId: branch.id },
      orderBy: [{ date: 'asc' }, { startMinute: 'asc' }],
      select: { id: true, date: true, startMinute: true, endMinute: true, seats: { select: { roomId: true }, distinct: ['roomId'] }, invigilations: { select: { roomId: true, staffId: true, room: { select: { name: true } } } } },
    });
    const bare = sessions.flatMap((s) => s.seats.filter((x) => !s.invigilations.some((i) => i.roomId === x.roomId)).map(() => s));
    if (bare.length) throw conflict('ROOMS_WITHOUT_INVIGILATOR', `${bare.length} room${bare.length === 1 ? ' has' : 's have'} no invigilator yet.`);
    const settings = await effectiveExamSettings(scope.school.id, branch.id, tx);
    const now = new Date();
    const updated = await tx.examTimetable.update({ where: { id: timetable.id }, data: { publishedAt: now, updatedAt: now, publications: { increment: 1 } } });
    let notified = 0;
    if (settings.notifyTimetable) {
      const duties = new Map();
      for (const s of sessions) for (const i of s.invigilations) duties.set(i.staffId, [...(duties.get(i.staffId) ?? []), { date: toDay(s.date), start: toClock(s.startMinute), end: toClock(s.endMinute), room: i.room.name }]);
      const created = await createNotifications(
        [...duties.entries()].map(([staffId, list]) => ({
          type: 'EXAM_DUTIES',
          recipientId: staffId,
          schoolId: scope.school.id,
          branchId: branch.id,
          subjectType: 'examination',
          subjectId: exam.id,
          params: { examination: exam.name, branch: branch.name, duties: list, republished: updated.publications > 1 },
          dedupeKey: `exam-duties:${timetable.id}:${updated.publications}:${staffId}`,
        })),
        { client: tx },
      );
      notified = created.length;
    }
    await audit(tx, scope, user, req, AUDIT_ACTIONS.EXAM_TIMETABLE_PUBLISHED, exam, branch, `Published the ${branch.name} timetable of ${exam.name}${notified ? `; ${notified} invigilators notified` : ''}.`, {
      fields: ['publishedAt'],
      branch: branch.name,
      publication: updated.publications,
      notified,
    });
  });
  return getTimetable(scope, examId, { branch: branchId });
}

