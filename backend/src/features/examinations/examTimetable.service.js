/*
 * Examination timetables (docs/business-rules.md → Examinations → Timetable), per examination and
 * branch: sessions, the papers sat in each, every student's room and seat, and every room's
 * invigilators. Generated by the engine (timetableEngine.js) from the choices given (shifts, rooms,
 * staff left out…), then adjusted by hand: a paper moved to another session (both sessions re-seated
 * and re-staffed), a room's invigilators replaced. Published to the invigilators (a notification
 * each, when the school's setting says so).
 *
 * Who: the School Owner for any branch; a Manager for their own branch (rooms and staff are the
 * branch's), of school-wide examinations and their branch's own. The whole timetable is generated or
 * cleared only before the examination starts; afterwards sessions before today are kept as they are.
 * Other examinations' sessions keep their rooms and invigilators: a room or person busy at the same
 * time elsewhere is not used. Writes take the school's examination lock and are audited.
 */

const actor = (user) => ({ id: user.id, name: user.name, role: user.role });
const brief = (x) => x && { id: x.id, name: x.name, ...(x.code !== undefined && { code: x.code }) };
const studentName = (s) => [s.firstName, s.middleName, s.lastName].filter(Boolean).join(' ');
/** The seating seed of a session: the timetable's seed, its date and its place in the day. */
const sessionSeed = (seed, date, sequence) => ((seed ?? 1) + Number(date.replaceAll('-', '')) * 31 + sequence * 7919) >>> 0;
const overlaps = (a, b) => a.date === b.date && a.startMinute < b.endMinute && b.startMinute < a.endMinute;

