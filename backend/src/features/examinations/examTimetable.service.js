/** The examination and the branch of the timetable the scope may see. */
async function context(client, scope, examId, branchId) {
  const exam = await findExam(client, scope, examId);
  const id = scope.branch ? scope.branch.id : (branchId ?? exam.branchId);
  if (!id) throw badRequest('Choose the branch.', { branch: 'Choose the branch of the timetable.' });
  if (exam.branchId && id !== exam.branchId) throw notFound('This examination is not held in that branch.');
  const branch = await client.branch.findFirst({ where: { id, schoolId: scope.school.id }, select: { id: true, name: true, code: true, status: true } });
  if (!branch) throw notFound('Branch not found.');
  return { exam, branch };
}

function writable(exam) {
  if (exam.status === 'CANCELLED') throw conflict('EXAM_CANCELLED', `${exam.name} was cancelled. Its timetable is kept as it is.`);
  if (exam.academicYear.status === 'CLOSED') throw conflict('YEAR_CLOSED', `${exam.academicYear.name} is closed.`);
}

/** Sections of the examination's classes in the branch, with their students now enrolled. */
async function loadSections(client, exam, branchId) {
  const classIds = exam.classes.map((c) => c.class.id);
  if (!classIds.length) return [];
  const rows = await client.section.findMany({
    where: { classId: { in: classIds }, academicYearId: exam.academicYearId, branchId, status: 'ACTIVE' },
    select: {
      id: true,
      name: true,
      classId: true,
      class: { select: { name: true } },
      enrollments: { where: { status: 'ACTIVE' }, select: { student: { select: { id: true, firstName: true, middleName: true, lastName: true, studentNumber: true } } } },
    },
    orderBy: [{ class: { sequence: 'asc' } }, { nameKey: 'asc' }],
  });
  return rows.map((s) => ({ id: s.id, classId: s.classId, name: sectionDisplayName(s.class.name, s.name), students: s.enrollments.map((e) => ({ id: e.student.id, name: studentName(e.student), number: e.student.studentNumber })) }));
}

/** Rooms and people busy in other examinations' sessions of the branch from..to: [{ date, startMinute, endMinute, rooms:Set, staff:Set }]. */
async function loadOtherSessions(client, exam, branchId, from, to) {
  const rows = await client.examSession.findMany({
    where: { branchId, examinationId: { not: exam.id }, examination: { status: { not: 'CANCELLED' } }, date: { gte: asDbDay(from), lte: asDbDay(to) } },
    select: { date: true, startMinute: true, endMinute: true, seats: { select: { roomId: true }, distinct: ['roomId'] }, invigilations: { select: { staffId: true, roomId: true } } },
  });
  return rows.map((r) => ({ date: toDay(r.date), startMinute: r.startMinute, endMinute: r.endMinute, rooms: new Set([...r.seats.map((s) => s.roomId), ...r.invigilations.map((i) => i.roomId)]), staff: new Set(r.invigilations.map((i) => i.staffId)) }));
}

/** Active staff of the branch, with the sections and subjects each teaches ('sectionId|subjectId'). */
async function loadStaff(client, exam, branchId, sectionIds) {
  const [people, teaching] = await Promise.all([
    client.user.findMany({ where: { role: 'STAFF', status: 'ACTIVE', branchId }, select: { id: true, name: true, staffId: true, jobTitle: true }, orderBy: { name: 'asc' } }),
    sectionIds.length
      ? client.teachingAssignment.findMany({
          where: { sectionId: { in: sectionIds }, role: 'SUBJECT_TEACHER', cancelledAt: null, subjectId: { not: null }, startDate: { lte: exam.endDate }, OR: [{ endDate: null }, { endDate: { gte: exam.startDate } }] },
          select: { teacherId: true, sectionId: true, subjectId: true },
        })
      : [],
  ]);
  return people.map((p) => ({ ...p, teaches: new Set(teaching.filter((t) => t.teacherId === p.id).map((t) => `${t.sectionId}|${t.subjectId}`)) }));
}

const touch = (tx, examId, branchId) => tx.examTimetable.updateMany({ where: { examinationId: examId, branchId }, data: { updatedAt: new Date() } });

const audit = (tx, scope, user, req, action, exam, branch, description, change) =>
  recordAuditEvent({ client: tx, action, actor: actor(user), target: { type: 'examination', id: exam.id, name: `${exam.name} (${branch.name})` }, schoolId: scope.school.id, description, change, req });

/** Deletes a branch's timetable rows of an examination (sessions, sittings, seats, invigilators). */
async function deleteRows(tx, examId, branchId, sessionWhere = {}) {
  const where = { examinationId: examId, branchId, ...sessionWhere };
  await tx.examInvigilation.deleteMany({ where: { session: where } });
  await tx.examSeat.deleteMany({ where: { session: where } });
  await tx.examSitting.deleteMany({ where: { session: where } });
  await tx.examSession.deleteMany({ where });
}

